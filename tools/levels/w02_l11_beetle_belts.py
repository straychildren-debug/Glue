"""Генератор уровня мира 2 «11 · Жуки на ленте» (очень сложный, на ловкость; вторая переделка после тестов).

Правило: в каждой части оба героя одновременно делают трудное в разных местах — один человек за двоих
не справится; и в каждой части есть приём, до которого надо додуматься. Жуки — отбойники: удар сбоку
отбрасывает героя (у шипов и ям — гибель), увидев героя, бросаются.

1. Педаль под отбойником. Дверь открыта, пока кто-то стоит на плите; на плиту бросается жук-отбойник —
   держать плиту, перепрыгивая его броски. Тем временем второй проскакивает дверь, коридор с пилой
   и дёргает рычаг — дверь остаётся открытой. По краям площадки — шипы.
2. Ступенька в воздухе и мост. Яма в 6 тайлов: первый прыгает и замирает в воздухе, второй с его головы —
   на тот берег и на плиту: из берега выдвигается мост под замершим. На берегу — отбойник: держать плиту,
   перепрыгивая его, пока товарищ не перейдёт.
3. Эскалатор и уступ. Лента к яме, навстречу — жуки-отбойники: прыжками. Финиш на уступе в 3 тайла:
   первый замирает у стены — второй с его головы наверх; первый оживает, подманивает бросальщика
   и замирает в последний миг — жук врезается и оглушён; с оглушённого жука, как со ступеньки, — наверх.
4. Загон: весы на 3 держат дальнюю дверь; ящик и двое — три, но пройти некому. Ящик к правому краю весов,
   замереть на левом — жук заперт на весах (ящик + жук + замерший); второй — в дверь, через яму, по
   встречной ленте с бегуном — к рычагу. Чекпоинт на уступе.

Запуск: python tools/levels/w02_l11_beetle_belts.py → levels/w02_l11_beetle_belts.tscn"""
from w2common import Level, paths, vec

BY = 28 / 64  # от центра жука до пола
D = 3.5  # на сколько части 2–3 правее (площадка части 1 расширена)
lv = Level('W02L11', '11 · Жуки на ленте', 95 + D, 'scaffolds', 'w02_lm11_beetle_statue.png')


def bumper(name, x, floor_y, direction, **extra):
    """Жук-отбойник-бросальщик; на плиты не давит."""
    lv.node(name, 'beetle', x, floor_y - BY, direction=f'{direction}', speed='200.0', aggressive='true',
            knockback='true', mass='0.0', sight_tiles='8.0', **extra)


# 1. Педаль под отбойником: площадка жука 8.5–16 между полосами шипов, дверь за ней.
lv.block(1, 13, 4, 5)   # старт на тайл ниже: жук видит только тех, кто на его высоте
lv.block(5, 12, 23 + D, 6)
lv.node('Spk1a', 'spikes', 7.75, 12, width_tiles='1.5')  # за ступенькой — разбег в 2 тайла
lv.node('Spk1b', 'spikes', 16.75, 12, width_tiles='1.5')
lv.node('Plate1', 'plate', 11, 12, mark_color='Color(0.95, 0.85, 0.3, 1)')
bumper('Bump1', 14, 12, -1)
lv.node('Door1', 'door', 15 + D, 8, size_tiles=vec(1, 4), triggers=paths('Plate1', 'Lever1'), open_offset_tiles=vec(0, -3.5),
        mark_color='Color(0.95, 0.85, 0.3, 1)')
lv.block(15 + D, -8, 13, 16)  # потолок над коридором: в дверь — только снизу
lv.node('Saw1', 'saw', 18 + D, 12 - 0.55, path_tiles=vec(5, 0), speed='260.0')  # за рельсом — разбег к яме
lv.node('Lever1', 'lever', 27 + D, 12, mark_color='Color(0.95, 0.85, 0.3, 1)')

# 2. Ступенька в воздухе и выдвижной мост.
lv.block(28 + D, 15, 6, 3)
lv.node('Pit2', 'spikes', 31 + D, 15, width_tiles='6.0')
lv.block(34 + D, 12, 11, 6)
lv.node('Bridge', 'door', 34 + D, 12, size_tiles=vec(6, 0.5), triggers=paths('Plate2'), open_offset_tiles=vec(-6, 0),
        mark_color='Color(0.4, 0.7, 0.95, 1)')
lv.node('Plate2', 'plate', 41 + D, 12, mark_color='Color(0.4, 0.7, 0.95, 1)')
bumper('Bump2', 44 + D, 12, -1)

# 3. Эскалатор и уступ.
lv.block(45 + D, 15, 2.5, 3)  # 2,5 тайла: жук проваливается и лопается (в 1,5 двое застревали поперёк — мост)
lv.node('Pit3', 'spikes', 46.25 + D, 15, width_tiles='2.5')
lv.block(47.5 + D, 12.375, 10, 5.625)
lv.node('Belt', 'conveyor', 47.5 + D, 12, width_tiles='10.0', speed='-260.0')
lv.block(47.5 + D, -8, 10, 8 + 9.6)  # низкий потолок над лентой
for i, (x, wait) in enumerate([(55.5 + D, 2.0), (56.6 + D, 3.1)]):
    lv.node(f'Runner{i + 1}', 'beetle', x, 12 - 0.375 - BY, direction='-1', speed='200.0', knockback='true',
            respawn_time=f'{wait}')
lv.block(57.5 + D, 12, 1.5, 6)      # закуток вровень с лентой: отсюда жук не видит — выбрать момент
lv.block(59 + D, 11, 6, 7)          # площадка жука на тайл выше
lv.block(62 + D, 8, 3, 3)           # уступ с финишем — 3 тайла над площадкой
bumper('Bump3', 60 + D, 11, 1)

# 4. Загон (третья версия, «11–14 — по мерке 15–16»). Весы на 3 держат дверь, только пока на них вес, и
# далеко от них: наступить и добежать не выйдет. Веса: ящик, двое, жук-тихоход (весит 1). Ящик и двое —
# это три, но тогда пройти некому. Догадка: загон — ящик (он у двери) придвинуть к правому краю весов,
# когда жук слева, и замереть на левом краю, когда жук между: жук заперт на весах, ящик + жук +
# замерший — три. Второй — в дверь, через яму, вверх по встречной ленте с бегуном — к рычагу: дверь
# открыта насовсем, замерший свободен.
lv.block(65 + D, 8, 13, 10)
lv.block(65 + D, -8, 13, 12)        # потолок над загоном (низ 4); над уступом части 3 — открыто
lv.node('Crate4', 'crate', 74 + D, 8 - 31 / 64)
lv.node('Walker4', 'beetle', 68 + D, 8 - BY, direction='1', speed='110.0')
lv.node('Plate4', 'plate', 70.3 + D, 8, width_tiles='3.0', threshold='3.0', mark_color='Color(0.35, 0.8, 0.4, 1)')
lv.node('Door4', 'door', 76.5 + D, 4, size_tiles=vec(1, 4), triggers=paths('Plate4', 'Lever4'), open_offset_tiles=vec(0, -3.5),
        close_speed='900.0', mark_color='Color(0.35, 0.8, 0.4, 1)')
lv.block(76.5 + D, -8, 1, 12)
lv.block(77.5 + D, 11, 1.5, 7)      # яма за дверью
lv.node('Pit4', 'spikes', 78.25 + D, 11, width_tiles='1.5')
lv.block(79 + D, 8.375, 10, 9.625)
lv.node('Belt4', 'conveyor', 79 + D, 8, width_tiles='10.0', speed='-240.0')
lv.block(77.5 + D, -8, 11.5, 13.6)  # низкий потолок над лентой (низ 5,6)
lv.node('Runner4', 'beetle', 88 + D, 8 - 0.375 - BY, direction='-1', speed='200.0', knockback='true', respawn_time='2.2')
lv.block(89 + D, 8, 5, 10)
lv.node('Lever4', 'lever', 90 + D, 8, mark_color='Color(0.35, 0.8, 0.4, 1)')
lv.node('Finish', 'finish', 92 + D, 8)

lv.checkpoints = [(2, 13), (26 + D, 12), (62.7 + D, 8)]
lv.write('w02_l11_beetle_belts.tscn')
