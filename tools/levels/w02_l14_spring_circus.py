"""Генератор уровня мира 2 «14 · Пружинный цирк» (очень сложный, на ловкость рук; переделка после тестов).

Изюминка — цирк: трапеции (движущиеся площадки) над пилами, батуты, взведённая пружина на трапецию.

1. Две трапеции. А стоит на верхней площадке, Б на нижней; трапеции трогаются, только когда на каждой
   по герою, и едут разом над пропастью с шипами. На каждом ярусе свои пилы на рельсах со своим ритмом:
   каждый в одно и то же время проходит свои — один человек за двоих не уследит. Пилы ходят вверх-вниз
   поперёк пути: проскочить под поднятой или перепрыгнуть опущенную, подгадав шагом по трапеции.
2. Батуты на столбах над шипами: с батута на батут, подруливая в воздухе; между ними вверх-вниз ходят
   пилы — проскакивать в такт; с последнего — на уступ.
3. Взведённая пружина на трапецию: замереть на батуте, товарищ на голову, ожить, когда трапеция
   отъехала от батута на шаг (раньше — удар головой о её днище, позже — не догнать), и в полёте рулить на неё. С неё прямо до выхода не допрыгнуть: прыжок с трапеции на высокий уступ.
4. «Двойка под куполом» (третья версия, «короткий и простой»): две трапеции-напарницы на двух ярусах
   едут, только пока на обеих стоят. На каждом ярусе по три пилы вверх-вниз со своим ритмом. Переждать
   свою пилу — отступить по трапеции или подпрыгнуть; но подпрыгнул — встали обе, и у товарища сбился
   такт. Подпрыгнувший летит вперёд со скоростью трапеции — рулить назад.
5. «Ловитор»: трапеция под куполом едет, как только на неё встали; второй взлетает с батута взведённой
   пружиной рядом с ней, ловитор хватает его за руку и проносит над пропастью, у уступа — раскачаться
   и спрыгнуть.
Чекпоинты: старт, после первых трапеций, перед «двойкой» (пружина и батуты — одним заходом; у «ловитора»
своего нет — сорвался, и «двойка» заново).

Запуск: python tools/levels/w02_l14_spring_circus.py → levels/w02_l14_spring_circus.tscn"""
from w2common import Level, paths, vec

lv = Level('W02L14', '14 · Пружинный цирк', 127, 'scaffolds', 'w02_lm14_spring_arena.png')
lv.slot_spawns = [(2.5, 8), (2.5, 12)]

# 1. Две трапеции над пропастью 6–22: верхний ярус (пол 8, потолок 4) и нижний (пол 12).
lv.block(1, -8, 23, 12)
lv.block(1, 8, 5, 1)
lv.block(1, 12, 5, 6)
lv.block(6, 16, 16, 2)
lv.node('PitSpikes', 'spikes', 14, 16, width_tiles='16.0')
for name, y, other in (('TrapezeU', 8, 'TrapezeL'), ('TrapezeL', 12, 'TrapezeU')):
    lv.node(name, 'mover', 6, y, size_tiles=vec(4, 0.5), path_tiles=vec(12, 0), speed='150.0',
            ride='true', partners=paths(other))
# Пилы ходят вверх-вниз поперёк пути: пройти под поднятой или перепрыгнуть опущенную; подгадать —
# шагом по трапеции вперёд-назад. Верхние — от потолка, нижние — не выше днища верхней трапеции.
# Пилы быстрые: опасны недолго, но окно надо поймать — ждать у заднего края и рывком под поднявшейся.
for name, x, top, path, spd, at in (('SawU1', 11, 4.55, 2.9, 300, 0.0), ('SawU2', 16.5, 4.55, 2.9, 340, 0.5),
                                    ('SawL1', 10, 9.0, 2.45, 280, 0.3), ('SawL2', 15, 9.0, 2.45, 320, 0.8)):
    lv.node(name, 'saw', x, top, path_tiles=vec(0, path), speed=f'{spd}.0', start_at=f'{at}')
lv.block(22, 8, 2, 1)                   # верхний причал — и вниз

# 2. Батуты на столбах 30, 35, 40 над шипами 28–43, между ними пилы вверх-вниз; уступ 43–60 на высоте 8.
lv.block(22, 12, 6, 6)
lv.block(28, 15, 15, 3)
lv.node('Spikes2', 'spikes', 35.5, 15, width_tiles='15.0')
for i, x in enumerate((30, 35, 40)):
    lv.block(x - 0.75, 12, 1.5, 3)
    lv.node(f'Pad{i + 1}', 'spring', x, 12)
lv.node('SawA', 'saw', 32.5, 12.5, radius_tiles='0.5', path_tiles=vec(0, -4.5), speed='170.0')
lv.node('SawB', 'saw', 37.5, 8.0, radius_tiles='0.5', path_tiles=vec(0, 4.5), speed='170.0')
lv.block(43, 8, 16.5, 10)

# 3. Взведённая пружина на трапецию (верх 2, ездит 49–59,5), с неё — на уступ выхода (верх 0).
lv.node('Pad4', 'spring', 50, 8)
lv.node('TrapezeTop', 'mover', 49, 2, size_tiles=vec(4.5, 0.5), path_tiles=vec(6, 0), speed='100.0', pause='3.0')
lv.block(59.5, 0.5, 8.5, 17.5)

# 4. «Двойка под куполом»: две трапеции-напарницы на ярусах −3,5 и 0,5 едут, только пока на обеих стоят:
# подпрыгнул один (переждать пилу) — встали обе, у товарища сбился такт его пил. Подпрыгнувший летит
# дальше со скоростью трапеции — рулить назад. На верхний ярус — две ступеньки (батут тут не достаёт).
lv.block(64, -1.5, 1.5, 1)
lv.block(66, -3.5, 2, 1)
lv.block(68, 6, 24, 12)
lv.node('PitSpikes4', 'spikes', 80, 6, width_tiles='24.0')
for name, y, other in (('DuoU', -3.5, 'DuoL'), ('DuoL', 0.5, 'DuoU')):
    lv.node(name, 'mover', 68, y, size_tiles=vec(3, 0.5), path_tiles=vec(21, 0), speed='190.0',
            ride='true', hold='true', partners=paths(other))
# верхние пилы — с купола до яруса; нижние — от днища верхней трапеции до нижнего яруса. Гуще, чем
# отступить по короткой трапеции: без пауз (подпрыгнуть или замереть — встают обе) не проехать.
SAWS = [('DuoSawU1', 73.5, -7.45, 3.4, 280, 0.0), ('DuoSawU2', 77.5, -7.45, 3.4, 320, 0.6),
        ('DuoSawU3', 81.5, -7.45, 3.4, 300, 0.3), ('DuoSawU4', 85.5, -7.45, 3.4, 340, 0.85),
        ('DuoSawL1', 75.5, -2.5, 2.45, 270, 0.5), ('DuoSawL2', 79.5, -2.5, 2.45, 310, 0.1),
        ('DuoSawL3', 83.5, -2.5, 2.45, 290, 0.8), ('DuoSawL4', 87.5, -2.5, 2.45, 330, 0.35)]
for name, x, top, path, spd, at in SAWS:
    lv.node(name, 'saw', x, top, path_tiles=vec(0, path), speed=f'{spd}.0', start_at=f'{at}')
lv.block(92, 0.5, 8, 17.5)

# 5. «Ловитор» (четвёртая версия: «11–14 — по мерке 15–16»): трапеция под куполом трогается, как только на
# неё встали, и едет над пропастью к дальнему уступу. Второй — с батута взведённой пружиной (замер и ожил):
# пролететь вверх рядом с трапецией, не под ней (удар головой о днище), — и ловитор хватает его за руку.
# Висящего трапеция проносит над шипами; у дальнего уступа — раскачаться и спрыгнуть.
lv.block(91, -1.5, 1.5, 0.5)            # полочка левее трапеции: на трапецию — с неё
lv.node('Catcher', 'mover', 93, -3.5, size_tiles=vec(3, 0.5), path_tiles=vec(20, 0), speed='150.0',
        ride='true', return_delay='1.5')
lv.node('Pad5', 'spring', 99.3, 0.5)
lv.block(100, 8, 17, 10)
lv.node('PitSpikes5', 'spikes', 108.5, 8, width_tiles='17.0')
lv.block(117, 0.5, 9, 17.5)
lv.node('Finish', 'finish', 122, 0.5)

lv.checkpoints = [(2.5, 12), (24, 12), (61, 0.5)]
lv.write('w02_l14_spring_circus.tscn')
