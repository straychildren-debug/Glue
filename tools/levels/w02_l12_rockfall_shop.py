"""Генератор уровня мира 2 «12 · Цех под обвалом» (очень сложный, на скорость; переделка после тестов).

Изюминка — погоня на двух этажах: А бежит наверху, Б внизу, сзади обвал на оба этажа. Двери на этаже
держат плиты на другом: оба встают на свои плиты, двери поднимаются (верхние) и опускаются (нижние) —
и оба срываются разом: через секунду после схода с плиты дверь товарища закрывается. Каждый на своём
этаже в это время делает своё: пила на рельсе, осыпающиеся настилы (стоять нельзя), отбойник у плиты.
Один человек за двоих не успевает: этажи требуют разного в одно и то же время.

1. Наверху пила; внизу осыпающийся мосток над шипами. Жёлтая пара.
2. Наверху осыпь и отбойник, бросающийся на синюю плиту; внизу пила и мосток. Синяя пара.
3. Перекрытие за синей дверью осыпается — верхний неизбежно падает вниз (прыжок с края — в дыру).
   Обратно наверх — взведённой пружиной: замереть на батуте под дырой и ожить. Зелёная пара.
4. Наверху пила и осыпь; внизу за порожком отбойник и яма с шипами. Фиолетовая пара — и вниз.
Третья версия («11–14 — по мерке 15–16»): ещё две пары после чекпоинта, обвал гонит дальше.
5. Наверх снова взведённой пружиной. Над обеими плитами ходят пилы: ждать товарища, перепрыгивая свою
   (сошёл с плиты — она держит дверь ещё секунду). За дверями — осыпь наверху и мосток внизу. Розовая пара.
6. Наверху отбойник у плиты, внизу пила над плитой, и плита держит дверь товарища лишь 0,6 с: срываться
   строго разом. За дверью верхний этаж обрывается — вниз, к выходу; внизу яма. Бирюзовая пара.

Этажи: верхний — пол 7, потолок 3; нижний — пол 13, потолок — перекрытие (низ 8).
Чекпоинты: после падения (оба внизу, у батута) и после четвёртой пары (у второго батута).
Запуск: python tools/levels/w02_l12_rockfall_shop.py → levels/w02_l12_rockfall_shop.tscn"""
from w2common import Level, COLORS, paths, vec

U, L = 7, 13          # верх пола верхнего и нижнего этажа
BY = 28 / 64          # от центра жука до пола
RELEASE = '1.0'       # сколько плита держит дверь товарища после схода
lv = Level('W02L12', '12 · Цех под обвалом', 106, 'scaffolds', 'w02_lm12_collapsed_hall.png')
lv.slot_spawns = [(2.5, U), (2.5, L)]

lv.block(1, -8, 104, 11)  # потолок верхнего этажа


def slab(x0, x1):
    """Перекрытие между этажами (его верх — пол верхнего этажа)."""
    lv.block(x0, U, x1 - x0, 1)


def crumble(name, x0, x1, y, t):
    lv.node(name, 'brittle', x0, y, width_tiles=f'{x1 - x0:g}', crumble_time=f'{t}')


def pit(name, x0, x1, bridge=0.0):
    """Яма с шипами в полу нижнего этажа (bridge > 0 — под осыпающимся мостком)."""
    lv.block(x0, 16, x1 - x0, 2)
    lv.node(name, 'spikes', (x0 + x1) / 2, 16, width_tiles=f'{x1 - x0:g}')
    if bridge:
        crumble('Crumble' + name[3:], x0, x1, L, bridge)


def pair(n, color, plate_u, door_u, plate_l, door_l, release=RELEASE):
    """Пара: плита наверху держит дверь внизу и наоборот."""
    c = COLORS[color]
    lv.node(f'PlateU{n}', 'plate', plate_u, U, release_delay=release, mark_color=c)
    lv.node(f'PlateL{n}', 'plate', plate_l, L, release_delay=release, mark_color=c)
    lv.node(f'DoorU{n}', 'door', door_u, 3, size_tiles=vec(1, 4), triggers=paths(f'PlateL{n}'),
            open_offset_tiles=vec(0, -4), mark_color=c)
    lv.node(f'DoorL{n}', 'door', door_l, 8, size_tiles=vec(1, 5), triggers=paths(f'PlateU{n}'),
            open_offset_tiles=vec(0, 5), mark_color=c)


def bumper(name, x, floor_y, direction):
    lv.node(name, 'beetle', x, floor_y - BY, direction=f'{direction}', speed='200.0', aggressive='true',
            knockback='true', mass='0.0', sight_tiles='7.0')


# Верхний этаж (перекрытие) и осыпающиеся куски в нём.
slab(1, 23)
crumble('CrumbleU1', 23, 26, U, 0.8)
slab(26, 37)
crumble('CrumbleU2', 37, 43, U, 0.35)   # верхний неизбежно падает вниз (и прыжок с края — в дыру)
slab(46, 56.5)                           # 43–46 — дыра над батутом
crumble('CrumbleU3', 56.5, 59, U, 0.7)
slab(59, 65.5)                           # дальше верхний этаж обрывается — вниз
slab(68.5, 80.5)                         # 65,5–68,5 — дыра над вторым батутом
crumble('CrumbleU5', 80.5, 83.5, U, 0.6)
slab(83.5, 96)                           # дальше — вниз, к выходу

# Нижний этаж: ямы с шипами (две — под осыпающимися мостками).
lv.block(1, L, 7, 5)
pit('PitL1', 8, 11, bridge=0.8)
lv.block(11, L, 19, 5)
pit('PitL2', 30, 32, bridge=0.6)
lv.block(32, L, 26, 5)
pit('PitL3', 58, 60)                     # перепрыгнуть
lv.block(60, L, 22, 5)
pit('PitL5', 82, 84.5, bridge=0.5)
lv.block(84.5, L, 14.5, 5)
pit('PitL6', 99, 101)
lv.block(101, L, 4, 5)

# 1. Наверху пила, внизу мосток над ямой.
lv.node('SawU1', 'saw', 8, U - 0.55, path_tiles=vec(4, 0), speed='240.0')
pair(1, 'yellow', 15.5, 19, 14, 17.5)
# 2. Наверху осыпь и отбойник у плиты, внизу пила и мосток.
lv.block(26, U - 0.5, 0.5, 0.5)  # порожек: отбойник ходит только у синей плиты
bumper('BumpU', 30, U, -1)
lv.node('SawL', 'saw', 23, L - 0.55, path_tiles=vec(5.5, 0), speed='220.0')
pair(2, 'blue', 32, 35, 33.5, 36.5)
# 3. Обмен: перекрытие осыпалось — оба внизу; взведённая пружина под дырой — вверх ровно один.
lv.node('Pad', 'spring', 44, L)
pair(3, 'green', 47.2, 49.3, 46.5, 49)
# 4. Наверху пила и осыпь, внизу отбойник у ямы.
lv.block(51, L - 0.5, 0.5, 0.5)  # порожек: за зелёной дверью два тайла спокойной земли
bumper('BumpL', 54.5, L, 1)
lv.node('SawU2', 'saw', 52.8, U - 0.55, path_tiles=vec(2.4, 0), speed='240.0')
pair(4, 'purple', 60.8, 63, 61.5, 63.5)

# 5. Наверх — второй взведённой пружиной. Над плитами ходят пилы: ждать товарища, перепрыгивая свою
# (пилы быстрые: медленную не перепрыгнуть — она проходит под ногами дольше прыжка).
lv.node('Pad2', 'spring', 67, L)
lv.node('SawU5', 'saw', 73.5, U - 0.55, path_tiles=vec(6, 0), speed='300.0')
lv.node('SawL5', 'saw', 73, L - 0.55, path_tiles=vec(6.5, 0), speed='280.0', start_at='0.5')
pair(5, 'pink', 77, 80.5, 77.5, 81)
# 6. Наверху отбойник у плиты, внизу пила над плитой; дверь товарища держится лишь 0,6 с.
lv.block(86, U - 0.5, 0.5, 0.5)  # порожек: отбойник ходит только у бирюзовой плиты
bumper('BumpU6', 89, U, -1)
lv.node('SawL6', 'saw', 86.5, L - 0.55, path_tiles=vec(6, 0), speed='320.0')
pair(6, 'teal', 90.5, 93, 90.5, 93.5, release='0.6')

lv.node('Finish', 'finish', 103, L)
lv.node('Crusher', 'crusher', -2.5, -8, height_tiles='27.0', speed='220.0', start_x_tiles='6.0',
        stop_x_tiles='64.0', catch_up_tiles='6.0', catch_up_speed='300.0')
# второй обвал — за розовыми дверями: гонит по осыпи к бирюзовой паре и к выходу
lv.node('Crusher2', 'crusher', 76, -8, height_tiles='27.0', speed='210.0', start_x_tiles='82.0',
        stop_x_tiles='100.0', catch_up_tiles='6.0', catch_up_speed='290.0')
lv.checkpoints = [(2.5, L), (41.5, L), (65, L)]
lv.write('w02_l12_rockfall_shop.tscn')
