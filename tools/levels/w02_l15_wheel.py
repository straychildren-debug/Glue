"""Генератор уровня мира 2 «15 · Беличье колесо» (очень сложный; заменяет «Два цеха» после тестов).

Изюминка — новый механизм: беличье колесо (src/mechanisms/wheel.gd). Бегущий в колесе стоит на месте
и раскручивает его; пока колесо крутится, открыты ворота, поднят подъёмник. Выпрыгнул — колесо
крутится по инерции и останавливается не сразу: маховик держит ворота, пока бежишь к ним.
Колёса стоят на подставках: мимо по полу проходишь, не попадая в колесо.

1. Колесо и ворота: один крутит — второй проходит; потом первый выпрыгивает и успевает сам.
2. Подъёмник от двух колёс: колесо внизу поднимает товарища на уступ, наверху — второе колесо
   того же подъёмника: теперь крутит тот, кто наверху, и поднимает первого.
3. Ворота на двух колёсах сразу и далеко: открыты, только пока крутятся оба. Раскрутить оба до
   полной и выпрыгнуть разом (дальний — не позже ближнего): маховика дальнему хватает впритык.
4. (третья версия, «короткий и довольно простой») Подъёмник под пилой: как во второй части, но поперёк
   шахты ходит пила. Колесо тянет не сразу и по инерции ещё тянет — крутящему трогаться в такт пиле.
5. Три колеса на двоих: ворота — пока крутятся все три; маховики разные. Догадка: раскрутить одно и,
   пока оно крутится по инерции, перебежать к другому; ближнее к воротам держит второй.
Чекпоинты: старт, уступ второй части, перед подъёмником под пилой (пятая — без своего).

Запуск: python tools/levels/w02_l15_wheel.py → levels/w02_l15_wheel.tscn"""
from w2common import Level, COLORS, paths, vec

lv = Level('W02L15', '15 · Беличье колесо', 80, 'scaffolds', 'w02_lm15_twin_halls.png')


def wheel(name, x, floor_y, color, coast='2.5'):
    """Колесо на подставке в 3 тайла и тайл высотой: дно колеса — верх подставки."""
    lv.block(x - 1.5, floor_y - 1, 3, 1)
    lv.node(name, 'wheel', x, floor_y - 1, mark_color=COLORS[color], coast_time=coast)


# 1. Колесо и ворота (комната 1–12, потолок 7).
lv.block(1, -8, 12, 15)
lv.block(1, 12, 12, 6)
wheel('Wheel1', 5, 12, 'yellow')
lv.node('Gate1', 'door', 11, 7, size_tiles=vec(1, 5), triggers=paths('Wheel1'), open_offset_tiles=vec(0, -5),
        close_speed='900.0', mark_color=COLORS['yellow'])

# 2. Подъёмник 18–20 от двух колёс: внизу (пол 12) и на уступе (верх 6), потолок 2.
lv.block(13, -8, 33, 10)
lv.block(13, 12, 5, 6)
lv.block(18, 12.5, 2, 5.5)               # шахта: внизу подъёмник вровень с полом
wheel('Wheel2', 15.5, 12, 'blue')
lv.node('Lift', 'door', 18, 12, size_tiles=vec(2, 0.5), triggers=paths('Wheel2', 'Wheel3'),
        open_offset_tiles=vec(0, -6), open_speed='160.0', close_speed='160.0', mark_color=COLORS['blue'])
lv.block(20, 6, 8, 12)
wheel('Wheel3', 24.5, 6, 'blue')

# 3. Ворота на двух колёсах (пол 12 от 28): стена с воротами на 41.
lv.block(28, 12, 19, 6)
wheel('Wheel4', 31, 12, 'green', coast='2.8')
wheel('Wheel5', 35, 12, 'green', coast='2.8')
lv.block(41, 2, 1, 6)
lv.node('Gate5', 'door', 41, 8, size_tiles=vec(1, 4), triggers=paths('Wheel4', 'Wheel5'), require_all='true',
        open_offset_tiles=vec(0, -4), close_speed='900.0', mark_colors='Array[Color]([%s, %s])' % (COLORS['green'], COLORS['green']))

# 4. Подъёмник под пилой (шахта 47–49, низ 12, верх 4): поперёк шахты на высоте 7,5 ходит пила.
# Крутящий колесо ведёт подъёмник с товарищем: колесо тянет не сразу и по инерции ещё тянет —
# трогаться в такт пиле; ездок ещё может сдвинуться по площадке.
lv.block(46, -8, 1, 17.5)               # левая стенка шахты (снизу проход на подъёмник)
lv.block(47, 12.5, 2, 5.5)
wheel('Wheel6', 44, 12, 'purple')
lv.node('Lift2', 'door', 47, 12, size_tiles=vec(2, 0.5), triggers=paths('Wheel6', 'Wheel7'),
        open_offset_tiles=vec(0, -8), open_speed='160.0', close_speed='160.0', mark_color=COLORS['purple'])
lv.node('ShaftSaw', 'saw', 44.5, 7.5, path_tiles=vec(6, 0), speed='260.0')
lv.block(49, 4, 30, 14)                 # верхний ярус 49–79 (верх 4)
lv.block(47, -8, 32, 7)                 # потолок над шахтой и ярусом (низ −1)
wheel('Wheel7', 52.5, 4, 'purple')

# 5. Три колеса на двоих: ворота открыты, только пока крутятся все три. Маховики разные: дальнее
# тяжёлое (крутится по инерции долго), среднее — меньше, ближнее к воротам — лёгкое. Один раскручивает
# дальнее, перебегает к среднему, раскручивает и бежит в ворота; ближнее всё это время крутит второй
# и выпрыгивает следом. В одиночку (все три по очереди) дальнее остановится раньше.
wheel('Wheel8', 57, 4, 'orange', coast='9.0')
wheel('Wheel9', 62, 4, 'orange', coast='3.8')
wheel('Wheel10', 67, 4, 'orange', coast='2.0')
lv.block(71, -1, 1, 1)
lv.node('Gate10', 'door', 71, 0, size_tiles=vec(1, 4), triggers=paths('Wheel8', 'Wheel9', 'Wheel10'), require_all='true',
        open_offset_tiles=vec(0, -4), close_speed='900.0',
        mark_colors='Array[Color]([%s, %s, %s])' % (COLORS['orange'], COLORS['orange'], COLORS['orange']))
lv.node('Finish', 'finish', 76, 4)

lv.checkpoints = [(2, 12), (21, 6), (42.5, 12)]
lv.write('w02_l15_wheel.tscn')
